import { execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { availableParallelism } from 'node:os';

const execFileAsync = promisify(execFile);

/**
 * 限并发地跑一批任务。每个任务都要启动一次 Prisma CLI，无上限地并行会在核数少的机器上
 * 互相抢 CPU，还会同时驻留十几个 Node 进程；按核数限流后既有并行收益又不至于压垮机器。
 */
const mapLimited = async (items, worker) => {
	const limit = Math.max(1, Math.min(4, availableParallelism?.() ?? 2));
	const results = new Array(items.length);
	let next = 0;
	await Promise.all(Array.from({ length: Math.min(limit, items.length) }, async () => {
		while (next < items.length) {
			const index = next++;
			results[index] = await worker(items[index], index);
		}
	}));
	return results;
};
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';

const projectDirectory = resolve(import.meta.dirname, '..');
const prismaBin = resolve(projectDirectory, 'node_modules/.bin/prisma');
const outputRootArgument = process.argv.find((argument) => argument.startsWith('--output-root='));
const migrationsRoot = resolve(projectDirectory, outputRootArgument ? outputRootArgument.slice('--output-root='.length) : 'migrations');
const nameArgument = process.argv.find((argument) => argument.startsWith('--name='));
/** 增量迁移的文件名后缀。只影响可读性，不参与任何判定。 */
const migrationName = (nameArgument ? nameArgument.slice('--name='.length) : 'schema_update').replace(/[^a-z0-9_]+/gi, '_').toLowerCase() || 'schema_update';
/**
 * 上一次生成迁移时的 schema 快照，按站点各存一份，**进版本库**。
 *
 * 它就是「已经生成到哪一版」的记录：下次生成时拿它当 diff 的起点，产出的才是增量而不是
 * 又一份全量建库脚本。没有它就只能 --from-empty，那样每次都覆写 0001——已有的库因为
 * 0001 早已记为应用，新增的表和索引永远落不下去。
 */
const snapshotDirectory = resolve(projectDirectory, 'prisma', '.applied');
const snapshotPath = (site) => join(snapshotDirectory, `${site}.prisma`);

const sites = ['global', 'base', 'passport', 'pve'];
const dialects = [
	{ name: 'sqlite', provider: 'sqlite', url: 'file:./database/default.sqlite' },
	{ name: 'mysql', provider: 'mysql', url: 'mysql://migration:secret@localhost/migration' },
	{ name: 'postgresql', provider: 'postgresql', url: 'postgresql://migration:secret@localhost/migration' },
];

const d1Seed = `INSERT INTO global_sites (key, name, base_site_key, dsn, database_binding, status, migration_status, is_default, is_system) VALUES ('global', '全局控制面', 'base', '', '', 'enabled', 'ready', 1, 1) ON CONFLICT(key, deleted_at) DO NOTHING;\nINSERT INTO base_tenants (created_at, updated_at, key, name, status) VALUES (0, 0, 'default', '默认租户', 'enabled') ON CONFLICT(key, deleted_at) DO NOTHING;\nINSERT INTO base_branches (created_at, updated_at, key, name, status) VALUES (0, 0, 'main', '主分站', 'enabled') ON CONFLICT(key, owner_tid, deleted_at) DO NOTHING;\nINSERT INTO base_bootstrap (created_at, updated_at, key, value) VALUES (0, 0, 'initial_admin', 'open') ON CONFLICT(key, owner_tid, deleted_at) DO NOTHING;`;

const generatedHeader = (site, dialect) => `-- Generated by Prisma migrate diff. Source: prisma/${site}.prisma (${dialect}).\n-- Do not edit this file directly; update the Prisma schema and rerun npm run prisma:migrations.\n\n`;
const generatedFile = (site, dialect, sql) => generatedHeader(site, dialect) + sql.trimEnd() + '\n';

/**
 * 把规范 schema 改写成某个方言能用的临时 schema。
 *
 * 快照也必须走同一套转换后再 diff：否则「enum 拆成 String」「Json 换成 String」这些
 * 方言差异会被当成 schema 变更，每次都 diff 出一堆假改动。
 */
const dialectSchema = (schema, provider) => {
	const enumDeclarations = [...schema.matchAll(/enum\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{([\s\S]*?)\}/g)];
	const enumNames = enumDeclarations.map((match) => match[1]);
	const enumValues = new Set(enumDeclarations.flatMap((match) => [...match[2].matchAll(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*$/gm)].map((value) => value[1])));
	let source = schema.replace(/provider\s*=\s*"(?:sqlite|mysql|postgresql)"/, `provider = "${provider}"`);
	if (provider === 'sqlite') {
		// SQLite/D1 has no enum type. Remove declarations and make enum fields
		// ordinary text fields; enum defaults must also become string literals.
		source = source.replace(/enum\s+[A-Za-z_][A-Za-z0-9_]*\s*\{[\s\S]*?\}\s*/g, '');
		if (enumNames.length) source = source.replace(new RegExp(`\\b(?:${enumNames.join('|')})\\b`, 'g'), 'String');
		source = source.replace(/@default\(([A-Za-z_][A-Za-z0-9_]*)\)/g, (match, value) => enumValues.has(value) ? `@default("${value}")` : match);
	}
	source = source
		// SQLite/D1 has no Prisma Json scalar; its temporary schema stores JSON as TEXT.
		.replace(provider === 'sqlite' ? /\bJson\b/g : /$^/, 'String')
		// PostgreSQL supports scalar lists natively. MySQL and SQLite/D1 do not, so
		// their temporary schemas store lists as serialized text and the adapters
		// perform the JSON serialization at bind time.
		.replace(provider === 'postgresql' ? /$^/ : /\bString\[\]/g, 'String')
		.replace(provider === 'postgresql' ? /$^/ : /@default\(\[\]\)/g, '@default("[]")')
		// Prisma's SQLite connector does not emit AUTOINCREMENT for BigInt primary keys.
		// Keep BigInt in the canonical schema and use Int only in this temporary SQLite
		// input so generated SQLite tables retain the required autoincrement behavior.
		.replace(provider === 'sqlite' ? /^(\s*id\s+)BigInt(\s+@id\s+@default\(autoincrement\(\)\))/gm : /$^/, '$1Int$2');
	return source;
};

/**
 * 生成从 from 到 to 的 SQL。from 为 undefined 表示空库（首次基线）。
 *
 * 每次调用都要启动一次 Prisma CLI（约 1 秒），因此调用方并行执行，见 main。
 */
const generatedSql = async (toSchema, fromSchema, provider, url, temporaryDirectory, fileName) => {
	const write = async (suffix, source) => {
		const path = join(temporaryDirectory, `${fileName}.${suffix}.${provider}.prisma`);
		await writeFile(path, source);
		return path;
	};
	const toPath = await write('to', dialectSchema(toSchema, provider));
	const from = fromSchema === undefined
		? ['--from-empty']
		: ['--from-schema-datamodel', await write('from', dialectSchema(fromSchema, provider))];
	const { stdout } = await execFileAsync(prismaBin, ['migrate', 'diff', ...from, '--to-schema-datamodel', toPath, '--script'], {
		cwd: projectDirectory,
		encoding: 'utf8',
		maxBuffer: 32 * 1024 * 1024,
		env: { ...process.env, DATABASE_URL: url },
	});
	return stdout;
};

/** 迁移目录里已用掉的最大编号。跨方言取同一个下一号，同一次改动在各方言里编号一致。 */
const usedNumbers = async (directory) => (await readdir(directory).catch(() => []))
	.map((name) => Number.parseInt(name.slice(0, 4), 10)).filter((value) => Number.isFinite(value));
const emptyDiff = (sql) => !sql.replace(/^\s*--.*$/gm, '').trim();

const outputDirectory = (dialect, site) => dialect === 'sqlite'
	? resolve(migrationsRoot, site)
	: resolve(migrationsRoot, dialect, site);

const main = async () => {
	const temporaryDirectory = await mkdtemp(join(tmpdir(), 'quick-react-prisma-schema-'));
	try {
		const schemas = new Map(await Promise.all(sites.map(async (site) =>
			[site, await readFile(resolve(projectDirectory, 'prisma', `${site}.prisma`), 'utf8')])));
		// 快照缺失 = 还没有基线，这一轮就用 --from-empty 产出全量 0001。
		const snapshots = new Map(await Promise.all(sites.map(async (site) =>
			[site, await readFile(snapshotPath(site), 'utf8').catch(() => undefined)])));

		// 站点 × 方言共十余次 Prisma CLI 调用，每次约 1 秒。串行执行会让构建、typecheck
		// 和迁移生成各等十几秒；它们互不依赖，并行后只受 CPU 限制。
		const jobs = sites.flatMap((site) => dialects.map((dialect) => ({ site, dialect })));
		const results = await mapLimited(jobs, async ({ site, dialect }) => ({
			site, dialect,
			sql: await generatedSql(schemas.get(site), snapshots.get(site), dialect.provider, dialect.url, temporaryDirectory, site),
		}));

		const written = [];
		for (const site of sites) {
			const rows = results.filter((item) => item.site === site);
			const baseline = snapshots.get(site) === undefined;
			// 增量为空说明这一版 schema 没有结构变化，什么都不写——写一个空迁移只会让
			// 编号越滚越大，而每个编号都是要在所有已有库上跑一遍的。
			if (!baseline && rows.every((item) => emptyDiff(item.sql))) continue;
			// 同一次改动在各方言里用同一个编号：出问题时按编号对照，不必猜哪个文件对哪个文件。
			const numbers = (await Promise.all(rows.map((item) => usedNumbers(outputDirectory(item.dialect.name, site))))).flat();
			const next = baseline ? 1 : Math.max(0, ...numbers) + 1;
			const fileName = baseline ? '0001_prisma_schema.sql' : `${String(next).padStart(4, '0')}_${migrationName}.sql`;
			for (const { dialect, sql } of rows) {
				if (!baseline && emptyDiff(sql)) continue;
				const directory = outputDirectory(dialect.name, site);
				await mkdir(directory, { recursive: true });
				await writeFile(join(directory, fileName), generatedFile(site, dialect.name, sql));
				written.push(`${dialect.name}/${site}/${fileName}`);
			}
		}

		// D1 吃的是一个扁平目录，SQLite 的 SQL 在 D1 上同样有效。
		const d1Root = resolve(migrationsRoot, 'd1');
		await mkdir(d1Root, { recursive: true });
		const d1Baseline = sites.every((site) => snapshots.get(site) === undefined);
		if (d1Baseline) {
			await mapLimited(sites, async (site, index) => {
				const sql = await generatedSql(schemas.get(site), undefined, 'sqlite', 'file:./database/default.sqlite', temporaryDirectory, `d1-${site}`);
				await writeFile(join(d1Root, `${String(index + 1).padStart(4, '0')}_prisma_${site}.sql`), generatedFile(site, 'd1', sql));
			});
			await writeFile(join(d1Root, '0005_prisma_seed.sql'), generatedFile('seed', 'd1', d1Seed));
		} else {
			// 增量往后追加。0005 是种子数据，新迁移排在它后面照常执行。
			let next = Math.max(0, ...await usedNumbers(d1Root)) + 1;
			for (const site of sites) {
				const sql = await generatedSql(schemas.get(site), snapshots.get(site), 'sqlite', 'file:./database/default.sqlite', temporaryDirectory, `d1-${site}`);
				if (emptyDiff(sql)) continue;
				const fileName = `${String(next++).padStart(4, '0')}_${site}_${migrationName}.sql`;
				await writeFile(join(d1Root, fileName), generatedFile(site, 'd1', sql));
				written.push(`d1/${fileName}`);
			}
		}

		// 快照最后才更新：中途失败时它仍指向上一版，重跑一次就是同样的结果。
		await mkdir(snapshotDirectory, { recursive: true });
		for (const site of sites) await writeFile(snapshotPath(site), schemas.get(site));
		console.log(written.length ? `生成 ${written.length} 个迁移文件：\n  ${written.join('\n  ')}` : 'Prisma Schema 未发生结构变化，没有需要生成的迁移');
	} finally {
		await rm(temporaryDirectory, { recursive: true, force: true });
	}
};

await main();
// 生成完顺手校验一次：快照刚更新过，这里应该恒为通过；不通过就说明生成器本身有问题，
// 现在报比等到下次 typecheck 报要好找得多。
execFileSync(process.execPath, [resolve(projectDirectory, 'scripts', 'verify-prisma-migrations.mjs')], {
	cwd: projectDirectory, stdio: 'inherit', env: { ...process.env, PRISMA_VERIFY_FORCE: '1' },
});
